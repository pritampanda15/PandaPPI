# pandappi/visualization/viewer_scripts.py
"""
Scripts that re-create the interface in a molecular viewer: PyMOL (.pml),
ChimeraX (.cxc), UCSF Chimera (.cmd) and VMD (.tcl). All are written from the
tidy interaction table, so every interaction type is covered the same way.

Van der Waals contacts are left out (thousands of lines); contacts without a
single named atom (ring contacts) show the residues but draw no distance.
"""

import os
from typing import Dict

import pandas as pd

from .interaction_map import DARK, GREY, INK, NAVY, ORANGE, RED, TEAL, TYPE_STYLE

VMD_COLOR = {TEAL: 'cyan', RED: 'red', NAVY: 'blue', INK: 'gray', DARK: 'black', ORANGE: 'orange', GREY: 'silver'}


def _contacts(df: pd.DataFrame) -> Dict[str, list]:
    """{type: [(chain1, resnum1, atom1, chain2, resnum2, atom2), ...]} without van der Waals."""
    out = {}
    for t, c1, r1, a1, c2, r2, a2, _ in df[df['Interaction_Type'] != 'Van der Waals'].itertuples(index=False):
        out.setdefault(t, []).append((c1, r1.split()[-1], a1, c2, r2.split()[-1], a2))
    return out


def _slug(label: str) -> str:
    return ''.join(ch if ch.isalnum() else '_' for ch in label.lower()).strip('_').replace('__', '_')


def _write(path: str, lines: list) -> str:
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return path


def write_pymol(df: pd.DataFrame, pdb_name: str, path: str) -> str:
    def sel(chain, num, atom=''):
        num = '\\' + num if num.startswith('-') else num  # PyMOL needs negative numbers escaped
        return f"(chain {chain} and resi {num}" + (f" and name {atom})" if atom else ")")

    lines = ['# PyMOL script generated by PandaPPI', f'load {pdb_name}, complex', 'hide everything', 'show cartoon',
             'color grey80', 'set cartoon_transparency, 0.6', 'bg_color white', 'set dash_width, 2.5', '']
    for label, rows in _contacts(df).items():
        name, n = _slug(label), 0
        lines.append(f'# {label} ({len(rows)})')
        for c1, r1, a1, c2, r2, a2 in rows:
            lines.append(f'show sticks, {sel(c1, r1)} or {sel(c2, r2)}')
            if a1 and a2:
                n += 1
                lines.append(f'distance {name}_{n:03d}, {sel(c1, r1, a1)}, {sel(c2, r2, a2)}')
        if n:
            lines += [f'color 0x{TYPE_STYLE.get(label, (INK,))[0][1:]}, {name}_*', f'group {name}, {name}_*']
        lines.append('')
    return _write(path, lines + ['util.cnc', 'zoom'])


def write_chimerax(df: pd.DataFrame, pdb_name: str, path: str) -> str:
    lines = ['# ChimeraX script generated by PandaPPI', f'open {pdb_name}', 'hide atoms', 'show cartoons',
             'color all lightgrey target c', 'transparency all 60 target c', 'set bgColor white', '']
    for label, rows in _contacts(df).items():
        lines.append(f'# {label} ({len(rows)})')
        for c1, r1, a1, c2, r2, a2 in rows:
            pair = f'/{c1}:{r1} /{c2}:{r2}'
            lines += [f'show {pair} atoms', f'style {pair} stick']
            if a1 and a2:
                lines.append(f'distance /{c1}:{r1}@{a1} /{c2}:{r2}@{a2}')
        lines.append('')
    return _write(path, lines + ['color byhetero', 'view'])


def write_chimera(df: pd.DataFrame, pdb_name: str, path: str) -> str:
    lines = ['# UCSF Chimera script generated by PandaPPI', f'open {pdb_name}', '~display', 'ribbon',
             'color gray,r', 'transparency 60,r', 'set bg_color white', '']
    for label, rows in _contacts(df).items():
        lines.append(f'# {label} ({len(rows)})')
        for c1, r1, a1, c2, r2, a2 in rows:
            lines += [f'display :{r1}.{c1}', f'display :{r2}.{c2}']
            if a1 and a2:
                lines.append(f'distance :{r1}.{c1}@{a1} :{r2}.{c2}@{a2}')
        lines.append('')
    return _write(path, lines + ['color byhet', 'focus'])


def write_vmd(df: pd.DataFrame, pdb_name: str, path: str) -> str:
    contacts = _contacts(df)
    residues = sorted({(c, r) for rows in contacts.values() for c1, r1, _, c2, r2, _ in rows
                       for c, r in ((c1, r1), (c2, r2))})
    shown = ' or '.join(f'(chain {c} and resid "{r}")' for c, r in residues)
    lines = ['# VMD script generated by PandaPPI', f'mol new {pdb_name}', 'mol delrep 0 top',
             'mol representation NewCartoon', 'mol color ColorID 8', 'mol selection all', 'mol material Transparent',
             'mol addrep top', 'mol representation Licorice 0.2 12 12', 'mol color Name',
             f'mol selection {{{shown}}}', 'mol material Opaque', 'mol addrep top', '',
             'proc contact {a b} {',
             '    set p [atomselect top $a]; set q [atomselect top $b]',
             '    if {[$p num] == 1 && [$q num] == 1} {',
             '        draw line [lindex [$p get {x y z}] 0] [lindex [$q get {x y z}] 0] style dashed width 3',
             '    }',
             '    $p delete; $q delete',
             '}', '']
    for label, rows in contacts.items():
        lines += [f'# {label} ({len(rows)})', f'draw color {VMD_COLOR.get(TYPE_STYLE.get(label, (INK,))[0], "gray")}']
        for c1, r1, a1, c2, r2, a2 in rows:
            if a1 and a2:
                lines.append(f'contact {{chain {c1} and resid "{r1}" and name "{a1}"}} '
                             f'{{chain {c2} and resid "{r2}" and name "{a2}"}}')
        lines.append('')
    return _write(path, lines + ['display resetview'])


def write_all(df: pd.DataFrame, pdb_file: str, output_prefix: str) -> Dict[str, str]:
    """Write all four scripts next to pdb_file. Returns {program: file}."""
    pdb_name = os.path.basename(pdb_file)  # scripts sit beside the structure, so a bare name loads it
    return {'PyMOL': write_pymol(df, pdb_name, f'{output_prefix}.pml'),
            'ChimeraX': write_chimerax(df, pdb_name, f'{output_prefix}.cxc'),
            'Chimera': write_chimera(df, pdb_name, f'{output_prefix}.cmd'),
            'VMD': write_vmd(df, pdb_name, f'{output_prefix}.tcl')}
